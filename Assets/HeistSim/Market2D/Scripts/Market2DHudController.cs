        /// <summary>Opens or closes the collapsible right Shift Dossier drawer.</summary>
        public void SetDrawerOpen(bool open)
        {
            _drawerOpen = open;
            if (_sidePanel != null)
            {
                _sidePanel.EnableInClassList("is-hidden", !open);
            }

            if (_drawerToggleWrap != null)
            {
                _drawerToggleWrap.EnableInClassList("is-hidden", open);
            }

            if (_zoomGroup != null)
            {
                _zoomGroup.EnableInClassList("zoom-group-shifted", open);
            }

            if (_promptStack != null)
            {
                _promptStack.EnableInClassList("prompt-stack-shifted", open);
            }

            if (open && _drawerUnreadDot != null)
            {
                _drawerUnreadDot.AddToClassList("is-hidden");
            }
        }

        /// <summary>Toggles the Shift Dossier drawer open or closed.</summary>
        public void ToggleDrawer()
        {
            SetDrawerOpen(!_drawerOpen);
        }

        /// <summary>Shows the unread coral dot on the drawer button when a notable event arrives while closed.</summary>
        public void MarkDrawerAttention()
        {
            if (!_drawerOpen && _drawerUnreadDot != null)
            {
                _drawerUnreadDot.RemoveFromClassList("is-hidden");
            }
        }

        /// <summary>True when a screen-space pointer coordinate lies inside the open Shift Dossier drawer.</summary>
        public bool IsScreenPointOverDrawer(Vector2 mouseScreenPos)
        {
            if (!_drawerOpen)
            {
                return false;
            }

            var w = Mathf.Max(1f, Screen.width);
            return mouseScreenPos.x >= w * (1f - ActiveRightPanelFrac);
        }

        /// <summary>Updates all HUD fields from the latest simulation snapshot and interaction probe.</summary>
        public void Refresh(in HeistSnapshot snapshot, in MarketActionHint hint)
        {
            if (_root == null)
            {
                BindElements();
                if (_root == null)
                {
                    return;
                }
            }

            var room = Iso2DMath.RoomAt(snapshot.Player);
            SetTextIfChanged(_zoneName, room.Name);

            _targetLoot = snapshot.StolenValue;
            if (!Application.isPlaying || snapshot.StolenValue <= _displayLoot)
            {
                _displayLoot = _targetLoot;
                var rounded = Mathf.RoundToInt(_displayLoot);
                SetTextIfChanged(_lootBig, "€" + rounded);
                SetTextIfChanged(_hudLootPill, "€" + rounded + " / €" + MarketData.Quota);
            }

            SetTextIfChanged(_lootQuota, "of €" + MarketData.Quota + " quota");

            var archLabel = snapshot.Arch switch
            {
                GuardArchitecture.StateTree => "ST+HTN",
                GuardArchitecture.Bt => "BT",
                _ => "FSM",
            };
            SetTextIfChanged(_squadArchPill, archLabel);
            SetButtonTextIfChanged(_btnSwitchAi, archLabel + " [Tab]");

            var worstState = WorstGuardState(snapshot.GuardState, snapshot.HasSecondGuard ? snapshot.Guard2State : null);
            var stateUpper = string.IsNullOrEmpty(worstState) ? "PATROL" : worstState.ToUpperInvariant();
            SetTextIfChanged(_guardChipText, (snapshot.HasSecondGuard ? "2G " : string.Empty) + stateUpper);

            var compactAlert = worstState switch
            {
                "attack" => "CAUGHT",
                "chase" => "ALERT",
                "investigate" => "INVEST",
                "search" => "SEARCH",
                _ => "CALM",
            };
            SetTextIfChanged(_hudAlertLabel, compactAlert);

            if (!string.Equals(_lastWorstGuardState, worstState, StringComparison.Ordinal))
            {
                _lastWorstGuardState = worstState;
                ApplyAlertDotClass(_guardDot, worstState);
                ApplyAlertDotClass(_hudAlertDot, worstState);
            }

            SetRoleBadge(_g1RoleIcon, snapshot.Guard1Role, visible: true, ref _hasLastG1Role, ref _lastG1Role, ref _lastG1Visible);
            SetRoleBadge(_g2RoleIcon, snapshot.Guard2Role, visible: snapshot.HasSecondGuard, ref _hasLastG2Role, ref _lastG2Role, ref _lastG2Visible);

            if (_hudBagPill != null)
            {
                SetTextIfChanged(_hudBagPill, snapshot.BagCount + "/" + MarketData.BagCapacity);
            }

            if (_hudRfPill != null)
            {
                _hudRfPill.EnableInClassList("is-hidden", snapshot.ActiveTags <= 0);
                if (snapshot.ActiveTags > 0)
                {
                    SetTextIfChanged(_hudRfPill, snapshot.ActiveTags + " RF");
                }
            }

            if (_statBag != null && (!Application.isPlaying || string.IsNullOrEmpty(_lastStamText)))
            {
                SetTextIfChanged(_statBag, snapshot.BagCount + " / " + MarketData.BagCapacity);
            }

            if (_statTags != null)
            {
                SetTextIfChanged(_statTags, snapshot.ActiveTags > 0 ? snapshot.ActiveTags + " tagged" : "Clean");
                _statTags.EnableInClassList("stat-value-alert", snapshot.ActiveTags > 0);
            }

            SetTextIfChanged(_statCctv, snapshot.CamerasDisabled ? "Offline" : "Online");

            var hasBackup = snapshot.BackupPhase != BackupPhase.None;
            if (_statRadio != null)
            {
                SetTextIfChanged(_statRadio, hasBackup ? "backup active!" : "radio quiet");
                _statRadio.EnableInClassList("stat-value-alert", hasBackup);
            }

            var tierIdx = Mathf.Clamp(snapshot.Tier, 0, HeistState.Tiers.Length - 1);
            var tier = HeistState.Tiers[tierIdx];
            var heatPct = Mathf.Clamp(snapshot.Heat * 100f, 0f, 100f);
            SetTextIfChanged(_heatTierLabel, tier.Label + " (" + Mathf.RoundToInt(heatPct) + "%)");

            _targetHeatPct = Mathf.Clamp(heatPct, 4f, 100f);
            if (!Application.isPlaying || Mathf.Abs(_displayHeatPct - _targetHeatPct) <= 0.1f)
            {
                _displayHeatPct = _targetHeatPct;
                if (_heatFill != null)
                {
                    _heatFill.style.width = Length.Percent(_displayHeatPct);
                }

                if (_hudHeatFill != null)
                {
                    _hudHeatFill.style.width = Length.Percent(_displayHeatPct);
                }
            }

            _objDone[0] = snapshot.CamerasDisabled;
            _objDone[1] = snapshot.VitrineOpen;
            _objDone[2] = snapshot.StolenValue >= MarketData.Quota;
            _objDone[3] = snapshot.StolenValue > 0f && snapshot.ActiveTags == 0;
            _objDone[4] = snapshot.Outcome == HeistOutcome.Escaped;

            var doneCount = 0;
            for (var i = 0; i < 5; i++)
            {
                if (_objDone[i])
                {
                    doneCount++;
                }

                if (_objBoxes[i] != null)
                {
                    _objBoxes[i].EnableInClassList("obj-box-done", _objDone[i]);
                }

                if (_objTexts[i] != null)
                {
                    _objTexts[i].EnableInClassList("obj-text-done", _objDone[i]);
                }
            }

            SetTextIfChanged(_objCount, doneCount + " / 5");

            var channelFrac = snapshot.ChannelHold > 0.001f
                ? Mathf.Clamp01(snapshot.ChannelProgress / snapshot.ChannelHold)
                : 0f;
            var channeling = channelFrac > 0.001f;
            if (_promptWrap != null)
            {
                var showPrompt = (hint.Found && !string.IsNullOrEmpty(hint.Prompt)) || channeling;
                if (showPrompt != _lastShowPrompt)
                {
                    _lastShowPrompt = showPrompt;
                    _promptWrap.EnableInClassList("is-hidden", !showPrompt);
                }

                if (showPrompt && _promptLabel != null)
                {
                    var nextPrompt = channeling
                        ? "Working · " + Mathf.RoundToInt(channelFrac * 100f) + "%"
                        : hint.Prompt;
                    if (!string.Equals(_lastPromptText, nextPrompt, StringComparison.Ordinal))
                    {
                        _lastPromptText = nextPrompt;
                        _promptLabel.text = nextPrompt;
                    }
                }

                if (_channelTrack != null && _channelFill != null)
                {
                    if (channeling != _lastChanneling)
                    {
                        _lastChanneling = channeling;
                        _channelTrack.EnableInClassList("is-hidden", !channeling);
                    }

                    var pct = Mathf.Round(channelFrac * 100f);
                    if (Mathf.Abs(pct - _lastChannelPct) > 0.5f)
                    {
                        _lastChannelPct = pct;
                        _channelFill.style.width = Length.Percent(pct);
                    }
                }
            }

            if (_activeRoomId != room.Id)
            {
                if (!string.IsNullOrEmpty(_activeRoomId) && _roomCells.TryGetValue(_activeRoomId, out var prev))
                {
                    prev.RemoveFromClassList("minimap-cell-active");
                }

                if (_roomCells.TryGetValue(room.Id, out var cur))
                {
                    cur.AddToClassList("minimap-cell-active");
                }

                _activeRoomId = room.Id;
            }

            _bagLookup.Clear();
            if (snapshot.Bag != null)
            {
                foreach (var id in snapshot.Bag)
                {
                    _bagLookup.Add(id);
                }
            }

            _roomsWithLoot.Clear();
            foreach (var loot in MarketData.Loot)
            {
                if (!_bagLookup.Contains(loot.Id))
                {
                    _roomsWithLoot.Add(loot.Room);
                }
            }

            foreach (var kv in _roomCells)
            {
                var hasLoot = _roomsWithLoot.Contains(kv.Key);
                if (!_lastRoomHasLoot.TryGetValue(kv.Key, out var prevHasLoot) || prevHasLoot != hasLoot)
                {
                    _lastRoomHasLoot[kv.Key] = hasLoot;
                    kv.Value.EnableInClassList("minimap-cell-has-loot", hasLoot);
                }
            }

            PlacePipIfChanged(0, _pipPlayer, snapshot.Player.x, snapshot.Player.y);
            PlacePipIfChanged(1, _pipGuard, snapshot.Guard.x, snapshot.Guard.y);
            if (_pipGuard2 != null)
            {
                var showG2 = snapshot.HasSecondGuard;
                if (!_lastPipGuard2Visible.HasValue || _lastPipGuard2Visible.Value != showG2)
                {
                    _lastPipGuard2Visible = showG2;
                    _pipGuard2.EnableInClassList("is-hidden", !showG2);
                }

                if (showG2)
                {
                    PlacePipIfChanged(2, _pipGuard2, snapshot.Guard2.x, snapshot.Guard2.y);
                }
            }

            PlacePipIfChanged(3, _pipStaff, snapshot.Staff.x, snapshot.Staff.y);
            PlacePipIfChanged(4, _pipExit, (float)MarketData.EasGate.I, (float)MarketData.EasGate.J);

            if (_outcomeOverlay != null)
            {
                var ended = snapshot.Outcome != HeistOutcome.None;
                if (!_lastEndModal.HasValue || _lastEndModal.Value != ended)
                {
                    _lastEndModal = ended;
                    _outcomeOverlay.EnableInClassList("is-hidden", !ended);
                }

                if (ended)
                {
                    SetTextIfChanged(_outcomeTitle, snapshot.Outcome == HeistOutcome.Escaped ? "Escaped" : "Busted");
                    SetTextIfChanged(_outcomeSub, snapshot.Outcome == HeistOutcome.Escaped
                        ? "Cleared Frischemarkt with €" + Mathf.RoundToInt(snapshot.StolenValue) + " in stolen goods. Press R for a new shift."
                        : "Caught by Frischemarkt security. Press R or click Reset to try again.");
                }
            }
        }

