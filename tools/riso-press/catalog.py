def make_empty_kind(kind_name: str) -> Dict[str, Any]:
    """Returns a copy of kind_name with the stealable merchandise removed (exact same shell, size, reach & pivot)."""
    base = MARKET_KINDS[kind_name]
    out = dict(base)
    shapes = list(base["shapes"])

    if kind_name == "liquor-cabinet":
        # Empty shelves + unlocked doors (no bottles, no gold lock dot)
        out["shapes"] = [
            shapes[0], shapes[1], shapes[2], shapes[3],
            # Open ajar glass doors (thin rim lines) + empty cabinet top
            shapes[15], shapes[16], shapes[18], shapes[19],
        ]
    elif kind_name == "action-table":
        # Bare pallet + blue bin + rim + sign pole & header (all 6 promo boxes stolen!)
        out["shapes"] = shapes[:3] + shapes[9:]
    elif kind_name == "pallet-stack":
        # Stripped down to the bare wooden Euro-pallet base (champagne boxes gone!)
        out["shapes"] = shapes[:2]
    elif kind_name == "chilled-case":
        # Empty refrigerated shelves behind glass doors (meat/salmon/dairy packs gone!)
        out["shapes"] = shapes[:4] + shapes[17:]
    elif kind_name == "checkout-lane":
        # Belt stripped of the razor-blade/merchandise boxes
        out["shapes"] = shapes[:6] + shapes[8:]
    elif kind_name == "gondola-shelf":
        # Structural frame, shelves, backpanel, pole & price strip (merchandise cleared!)
        keep = []
        for s in shapes:
            if "pole" in s or "panel" in s or "lines" in s:
                keep.append(s)
            elif "box" in s:
                b = s["box"]
                # Keep wide structural frame/shelf/base boxes (width >= 2.0)
                if b[3] >= 2.0:
                    keep.append(s)
        out["shapes"] = keep
    elif kind_name == "produce-island":
        # Wooden base, slats, 4 empty crates, price tags (all fruit/cheese balls gone!)
        out["shapes"] = [s for s in shapes if "ball" not in s]
    elif kind_name == "seasonal-display":
        # Bare wooden octabin plinth & sign (Advent candle stack gone!)
        out["shapes"] = [shapes[0], shapes[-1]]
    elif kind_name == "pallet-cage":
        # Empty wire mesh cage (BBQ grill cartons inside gone!)
        out["shapes"] = [shapes[0]] + shapes[3:]
    elif kind_name == "wine-rack":
        # Walnut frame, cream backing & brass shelf rails (all prosecco/wine bottles gone!)
        out["shapes"] = [s for s in shapes if "cyl" not in s]
    elif kind_name == "deli-counter":
        # Bare stainless counter + glass hood (truffle ham & cheese removed!)
        out["shapes"] = [shapes[0], shapes[1], shapes[4], shapes[5]]
    elif kind_name == "freezer-wall":
        # Empty icy freezer cabinet, rails, glass doors & handles (langoustine boxes gone!)
        out["shapes"] = shapes[:4] + shapes[10:]
    elif kind_name == "crate-tower":
        # Stripped down to bare wooden pallet base (all stacked espresso crates gone!)
        out["shapes"] = [shapes[0]]
    return out


def make_open_vitrine_kind() -> Dict[str, Any]:
    """Unlocked spirits vitrine (forced open, lock gone, bottles still inside ready to steal)."""
    base = MARKET_KINDS["liquor-cabinet"]
    out = dict(base)
    shapes = list(base["shapes"])
    # Drop the golden lock dot (index 17) and add a subtle teal unlocked indicator dot
    out["shapes"] = shapes[:17] + [{"dot": [0.90, 0.76, 1.05], "color": "teal", "r": 2.4}] + shapes[18:]
    return out
