        private void RenderLogs()
        {
            if (_logRows == null)
            {
                return;
            }

            for (var i = 0; i < LogCapacity; i++)
            {
                if (_logRows[i] == null)
                {
                    continue;
                }

                if (i < _logs.Count)
                {
                    _logRows[i].RemoveFromClassList("is-hidden");
                    var (tag, msg) = _logs[i];
                    if (_logTags[i] != null)
                    {
                        _logTags[i].text = tag;
                        _logTags[i].EnableInClassList("log-tag-alarm", tag == "ALARM" || tag == "CCTV");
                    }

                    if (_logMsgs[i] != null)
                    {
                        _logMsgs[i].text = msg;
                    }
                }
                else
                {
                    _logRows[i].AddToClassList("is-hidden");
                }
            }
        }

        private void SetRoleBadge(
            VisualElement slot,
            GuardTacticalRole role,
            bool visible,
            ref bool hasLast,
            ref GuardTacticalRole lastRole,
            ref bool lastVisible)
        {
            if (slot == null)
            {
                return;
            }

            if (hasLast && lastRole == role && lastVisible == visible)
            {
                return;
            }

            hasLast = true;
            lastRole = role;
            lastVisible = visible;

            slot.EnableInClassList("is-hidden", !visible);
            if (!visible)
            {
                return;
            }

            var sprite = RoleSpriteFor(role);
            if (sprite != null)
            {
                slot.style.backgroundImage = new StyleBackground(sprite);
            }
        }

        private Sprite RoleSpriteFor(GuardTacticalRole role)
        {
            return role switch
            {
                GuardTacticalRole.PrimaryPursuer => rolePursuerIcon,
                GuardTacticalRole.ExitInterceptor => roleInterceptorIcon,
                GuardTacticalRole.SabotageResponder => roleSabotageIcon,
                GuardTacticalRole.SectorSweeper => roleSweeperIcon,
                _ => rolePatrolIcon,
            };
        }

