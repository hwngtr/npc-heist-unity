        private static void ApplyAlertDotClass(VisualElement dot, string worstState)
        {
            if (dot == null)
            {
                return;
            }

            dot.RemoveFromClassList("guard-dot-warn");
            dot.RemoveFromClassList("guard-dot-alert");
            if (worstState == "chase" || worstState == "attack")
            {
                dot.AddToClassList("guard-dot-alert");
            }
            else if (worstState == "investigate" || worstState == "search")
            {
                dot.AddToClassList("guard-dot-warn");
            }
        }

        private static string WorstGuardState(string s1, string s2)
        {
            return AlertRank(s2) > AlertRank(s1) ? s2 : s1;
        }

        private static int AlertRank(string state)
        {
            return state switch
            {
                "attack" => 4,
                "chase" => 3,
                "investigate" => 2,
                "search" => 2,
                "return" => 1,
                _ => 0,
            };
        }

        private static string DirectionArrow(float deg)
        {
            if (deg >= -22.5f && deg < 22.5f) return "→";
            if (deg >= 22.5f && deg < 67.5f) return "↗";
            if (deg >= 67.5f && deg < 112.5f) return "↑";
            if (deg >= 112.5f && deg < 157.5f) return "↖";
            if (deg >= -67.5f && deg < -22.5f) return "↘";
            if (deg >= -112.5f && deg < -67.5f) return "↓";
            if (deg >= -157.5f && deg < -112.5f) return "↙";
            return "←";
        }

        private void PlacePipIfChanged(int slotIdx, VisualElement pip, float tileI, float tileJ)
        {
            if (pip == null)
            {
                return;
            }

            var xPct = Mathf.Clamp(tileI / MarketData.WidthTiles * 100f, 1f, 96f);
            var yPct = Mathf.Clamp(tileJ / MarketData.HeightTiles * 100f, 2f, 92f);
            var xKey = Mathf.RoundToInt(xPct * 10f);
            var yKey = Mathf.RoundToInt(yPct * 10f);
            if (_lastPipXPct[slotIdx] == xKey && _lastPipYPct[slotIdx] == yKey)
            {
                return;
            }

            _lastPipXPct[slotIdx] = xKey;
            _lastPipYPct[slotIdx] = yKey;
            pip.style.left = Length.Percent(xPct);
            pip.style.top = Length.Percent(yPct);
        }

